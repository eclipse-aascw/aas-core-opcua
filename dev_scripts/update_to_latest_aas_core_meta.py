"""Fetch the latest models from aas-core-meta repository and re-generate the nodesets."""

import os.path
import pathlib
import re
import shlex
import subprocess
import sys
import xml.etree.ElementTree as ET

import requests

# NOTE (aaronzi, 2026-11-05):
# The meta-model is copied verbatim from aas-core-meta, so we attribute it to
# its authors. The upstream file does not carry a license header itself.
#
# REUSE-IgnoreStart
_META_MODEL_LICENSE_HEADER = """\
# SPDX-FileCopyrightText: 2024 aas-core-meta AUTHORS
#
# SPDX-License-Identifier: MIT

"""
# REUSE-IgnoreEnd

# NOTE (aaronzi, 2026-11-05):
# aas-core-codegen does not emit any copyright or license information, so we
# prepend the header to the generated nodeset ourselves. Otherwise, the header
# would be lost on every re-generation.
#
# REUSE-IgnoreStart
_NODESET_LICENSE_HEADER = """\
<!--
SPDX-FileCopyrightText: 2025 aas-core-opcua AUTHORS

SPDX-License-Identifier: MIT
-->

"""
# REUSE-IgnoreEnd

_XML_DECLARATION_RE = re.compile(r"\A<\?xml[^>]*\?>[ \t]*\n\s*")

_LEADING_SPDX_COMMENT_RE = re.compile(r"\A<!--\s*SPDX-.*?-->\s*", re.DOTALL)


def _prepend_nodeset_license_header(text: str) -> str:
    """
    Replace any leading SPDX comment in the nodeset ``text`` with our license header.

    The header is placed after the XML declaration, if there is one.
    """
    declaration = ""
    match = _XML_DECLARATION_RE.match(text)
    if match is not None:
        declaration = match.group(0).rstrip() + "\n\n"
        text = text[match.end() :]

    text = _LEADING_SPDX_COMMENT_RE.sub("", text, count=1)
    return declaration + _NODESET_LICENSE_HEADER + text


def _add_license_header_to_nodeset(path: pathlib.Path) -> None:
    """Prepend the license header to the nodeset generated by aas-core-codegen."""
    text = path.read_text(encoding="utf-8")
    path.write_text(_prepend_nodeset_license_header(text), encoding="utf-8")


def main() -> int:
    """Execute the main routine."""
    repo = "aas-core-works/aas-core-meta"
    branch = "main"
    rel_paths = [pathlib.Path("aas_core_meta/v3.py")]

    repo_dir = pathlib.Path(os.path.realpath(__file__)).parent.parent
    dev_scripts_dir = repo_dir / "dev_scripts"
    aas_metamodels_dir = repo_dir / "dev_scripts" / "aas_metamodels"

    # Get the Atom feed and extract the latest commit SHA
    feed_url = f"https://github.com/{repo}/commits/{branch}.atom"
    print(f"Fetching Atom feed: {feed_url}")
    try:
        response = requests.get(feed_url, timeout=30)
        response.raise_for_status()
    except Exception as e:
        print(f"Failed to fetch Atom feed: {e}", file=sys.stderr)
        return 1

    try:
        root = ET.fromstring(response.content)
        ns = {"atom": "http://www.w3.org/2005/Atom"}
        first_entry = root.find("atom:entry", ns)
        if first_entry is None:
            print("No entry found in Atom feed", file=sys.stderr)
            return 1

        id_text = first_entry.findtext("atom:id", default="", namespaces=ns)
        prefix = "tag:github.com,2008:Grit::Commit/"
        if not id_text.startswith(prefix):
            print(f"Unexpected ID format: {id_text}", file=sys.stderr)
            return 1

        revision = id_text[len(prefix) :]
        print(f"Latest commit SHA: {revision}")
    except Exception as e:
        print(f"Failed to parse Atom feed: {e}", file=sys.stderr)
        return 1

    # Download each file and prepend comment
    aas_metamodels_dir.mkdir(parents=True, exist_ok=True)

    for rel_path in rel_paths:
        raw_url = (
            f"https://raw.githubusercontent.com/{repo}/{revision}/{rel_path.as_posix()}"
        )
        print(f"Downloading: {raw_url}")
        response = requests.get(raw_url, timeout=30)
        response.raise_for_status()
        content = response.text

        comment = f"# Downloaded from: {raw_url}\n# Revision: {revision[:7]}\n\n"
        full_content = _META_MODEL_LICENSE_HEADER + comment + content

        aas_metamodel_file = aas_metamodels_dir / rel_path.name
        aas_metamodel_file.write_text(full_content, encoding="utf-8")

    print("AAS meta-models updated.")

    for rel_path in rel_paths:
        aas_metamodel_file = aas_metamodels_dir / rel_path.name

        snippets_dir = dev_scripts_dir / "snippets" / rel_path.stem

        output_dir = repo_dir / "nodesets" / rel_path.stem

        print(
            f"Generating the OPC UA nodeset for {rel_path} ...\n"
            f"  with snippets: {snippets_dir}\n"
            f"  and model: {aas_metamodel_file}\n"
            f"  to: {output_dir}"
        )

        cmd = [
            sys.executable,
            "-m",
            "aas_core_codegen",
            "--model",
            str(aas_metamodel_file),
            "--snippets",
            str(snippets_dir),
            "--target",
            "opcua",
            "--output_dir",
            str(output_dir),
        ]

        completed_process = subprocess.run(cmd, cwd=str(dev_scripts_dir), check=False)
        if completed_process.returncode != 0:
            cmd_joined = " ".join(shlex.quote(arg) for arg in cmd)
            print(f"Command failed: {cmd_joined}", file=sys.stderr)
            sys.exit(1)

        _add_license_header_to_nodeset(output_dir / "nodeset.xml")

    return 0


if __name__ == "__main__":
    sys.exit(main())
